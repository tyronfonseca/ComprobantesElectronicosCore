const std::vector<MonedaInfo>& Monedas::GetTodas() {
    return kMonedas;
}

const MonedaInfo* Monedas::GetPorCodigo(std::string_view codigo) {
    for (const auto& m : kMonedas) {
        if (m.codigo == codigo) {
            return &m;
        }
    }
    return nullptr;
}

bool Monedas::EsValida(std::string_view codigo) {
    return GetPorCodigo(codigo) != nullptr;
}

std::string Monedas::GetSimbolo(std::string_view codigo) {
    const auto* m = GetPorCodigo(codigo);
    return m ? m->simbolo : "";
}

std::string Monedas::GetDescripcion(std::string_view codigo) {
    const auto* m = GetPorCodigo(codigo);
    return m ? m->descripcion : "";
}

